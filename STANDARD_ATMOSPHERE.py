"""Standard Atmosphere Calculator (ISA) - temperature, pressure, density vs altitude."""
import os
import numpy as np
import matplotlib.pyplot as plt

# Constants
G0 = 9.80665      # gravity, m/s^2
R = 287.058       # specific gas constant for air, J/(kg K)
T0 = 288.15       # sea-level temperature, K
P0 = 101325.0     # sea-level pressure, Pa

# ISA layers: (base altitude in m, temperature lapse rate in K/m)
LAYERS = [
    (0, -0.0065),       # troposphere
    (11000, 0.0),       # tropopause (isothermal)
    (20000, 0.001),     # lower stratosphere
]


def isa(h):
    """Return temperature (K), pressure (Pa), density (kg/m^3) at altitude h (m)."""
    t_b, p_b = T0, P0
    for i, (h_b, lapse) in enumerate(LAYERS):
        h_top = LAYERS[i + 1][0] if i + 1 < len(LAYERS) else float("inf")
        dh = min(h, h_top) - h_b
        if lapse != 0:
            t = t_b + lapse * dh
            p = p_b * (t / t_b) ** (-G0 / (lapse * R))
        else:
            t = t_b
            p = p_b * np.exp(-G0 * dh / (R * t_b))
        if h <= h_top:
            return t, p, p / (R * t)
        t_b, p_b = t, p


def main():
    altitudes = np.arange(0, 32001, 100)
    data = np.array([isa(h) for h in altitudes])
    temp, pres, dens = data[:, 0], data[:, 1], data[:, 2]

    # Print a small table
    print(f"{'Alt (m)':>8} {'T (K)':>8} {'P (Pa)':>10} {'rho (kg/m3)':>12}")
    for h in [0, 2000, 5000, 8000, 11000, 15000, 20000, 25000, 30000]:
        t, p, rho = isa(h)
        print(f"{h:>8} {t:>8.2f} {p:>10.1f} {rho:>12.4f}")

    # Plot
    fig, axes = plt.subplots(1, 3, figsize=(13, 5), sharey=True)
    km = altitudes / 1000
    axes[0].plot(temp, km, color="tab:red")
    axes[0].set_xlabel("Temperature (K)")
    axes[1].plot(pres / 1000, km, color="tab:blue")
    axes[1].set_xlabel("Pressure (kPa)")
    axes[2].plot(dens, km, color="tab:green")
    axes[2].set_xlabel("Density (kg/m³)")
    axes[0].set_ylabel("Altitude (km)")
    for ax in axes:
        ax.grid(True, alpha=0.3)
        ax.axhline(11, color="gray", ls="--", lw=0.8)  # tropopause
    fig.suptitle("International Standard Atmosphere (ISA)")
    plt.tight_layout()
    # Save to current working directory in Colab / Jupyter
    out_path = "atmosphere_plot.png"
    plt.savefig(out_path, dpi=150)
    print("\nSaved plot to", os.path.abspath(out_path))
    plt.show()  # open the plot in a window


if __name__ == "__main__":
    main()